const {app,BrowserWindow}=require('electron');
const path=require('path');const fs=require('fs');
app.setPath('userData',path.join(__dirname,'dist','history-check-profile'));
app.whenReady().then(async()=>{
 const win=new BrowserWindow({show:false,width:1400,height:900,webPreferences:{backgroundThrottling:false}});
 try{
  await win.loadFile('index.html');win.showInactive();
  const result=await win.webContents.executeJavaScript(`(async()=>{
    const checks=[];const assert=(value,label)=>{if(!value)throw Error(label);checks.push(label)};
    const flush=()=>new Promise(r=>setTimeout(r,0));
    const initial=borderRange.value;
    borderRange.value='45';borderRange.dispatchEvent(new Event('change',{bubbles:true}));await flush();
    await editHistory.undo();assert(borderRange.value===initial,'undo parameter');
    await editHistory.redo();assert(borderRange.value==='45','redo parameter');
    headlineInput.value='Test title';headlineInput.dispatchEvent(new Event('input',{bubbles:true}));
    await editHistory.undo();assert(headlineInput.value!=='Test title','undo pending text');
    await editHistory.redo();assert(headlineInput.value==='Test title','redo text');
    const bytes=await (await fetch('assets/template-classic.jpg')).arrayBuffer();
    await handleFiles([new File([bytes],'one.jpg',{type:'image/jpeg'})]);
    const id=currentPhotoId,url=photoItems[0].url;
    await editHistory.undo();assert(photoItems.length===0,'undo import');
    await editHistory.redo();assert(photoItems.length===1 && currentPhotoId===id,'redo import');
    rotateButton.click();await flush();await editHistory.undo();assert(photoRotation===0,'undo rotation');
    await editHistory.redo();assert(photoRotation===90,'redo rotation');
    const oldTemplate=currentTemplate;
    document.querySelector('[data-template="plainWhite"]').click();await flush();
    await editHistory.undo();assert(currentTemplate===oldTemplate,'undo template');
    await editHistory.redo();assert(currentTemplate==='plainWhite','redo template');
    await clearPhoto();assert(photoItems.length===0,'delete photo');
    await editHistory.undo();assert(photoItems.length===1,'undo deletion');
    assert((await fetch(url)).ok,'deleted blob remains readable');
    await editHistory.redo();assert(photoItems.length===0,'redo deletion');
    await editHistory.undo();
    applyAllButton.click();await flush();assert(applyToAllEnabled,'enable sync');
    await editHistory.undo();assert(!applyToAllEnabled,'undo sync');
    await editHistory.redo();assert(applyToAllEnabled,'redo sync');
    exportQualityRange.value='80';exportQualityRange.dispatchEvent(new Event('change',{bubbles:true}));await flush();
    await editHistory.undo();await editHistory.redo();assert(exportQualityRange.value==='80','redo export setting');
    const deleting=clearAllPhotos();confirmOkButton.click();await deleting;
    await editHistory.undo();assert(photoItems.length===1,'undo clear all');
    await editHistory.redo();assert(photoItems.length===0,'redo clear all');
    await editHistory.undo();borderRange.value='55';borderRange.dispatchEvent(new Event('change',{bubbles:true}));await flush();
    const position=editHistory.position;await editHistory.redo();assert(editHistory.position===position && borderRange.value==='55','new edit discards redo branch');
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,bubbles:true}));await new Promise(r=>setTimeout(r,200));
    assert(borderRange.value!=='55','Ctrl Z keyboard');
    document.dispatchEvent(new KeyboardEvent('keydown',{key:'z',ctrlKey:true,shiftKey:true,bubbles:true}));await new Promise(r=>setTimeout(r,200));
    assert(borderRange.value==='55','Ctrl Shift Z keyboard');
    const startPosition=editHistory.position;
    borderRange.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}));
    for(const value of ['60','65','70']){borderRange.value=value;borderRange.dispatchEvent(new Event('input',{bubbles:true}));}
    borderRange.dispatchEvent(new PointerEvent('pointerup',{bubbles:true}));await flush();
    assert(editHistory.position===startPosition+1,'slider gesture groups into one step');
    await editHistory.undo();assert(borderRange.value==='55','undo whole slider gesture');
    await editHistory.redo();assert(borderRange.value==='70','redo whole slider gesture');
    resetButton.click();await flush();await editHistory.undo();assert(borderRange.value==='70','undo restore defaults');
    const previousTheme=document.documentElement.dataset.theme;
    document.getElementById('themeToggle').click();await flush();await editHistory.undo();
    assert(document.documentElement.dataset.theme===previousTheme,'undo theme');
    const oldWatermark=watermarkImage.getAttribute('src')||'';
    const mark=new DataTransfer();mark.items.add(new File([bytes],'mark.jpg',{type:'image/jpeg'}));
    watermarkFileInput.files=mark.files;watermarkFileInput.dispatchEvent(new Event('change',{bubbles:true}));
    await new Promise(r=>setTimeout(r,150));
    await editHistory.undo();assert((watermarkImage.getAttribute('src')||'')===oldWatermark,'undo watermark upload');
    await editHistory.redo();assert(watermarkFileName.textContent==='mark.jpg','redo watermark upload');
    return checks;
  })()`);
  fs.writeFileSync(path.join(__dirname,'dist','history-check-result.json'),JSON.stringify(result,null,2));app.exit(0);
 }catch(error){fs.writeFileSync(path.join(__dirname,'dist','history-check-result.json'),String(error));app.exit(1)}
});
